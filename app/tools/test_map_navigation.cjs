"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../scrap_editor_app/web/companion_waypoints.js"), "utf8"), sandbox);
const map = sandbox.window.CompanionWaypointSymbols;
const bounds = [-4, 3, -3, 2];
const terrain = { key: "terrain-0", x: -4, y: 2 };
const topLeft = map.mapPoint(terrain, bounds, 800, 600);
assert.equal(topLeft.x, 50);
assert.equal(topLeft.y, 50);
const player = map.mapPoint({ kind: "Player", x: -3.5, y: 2.5 }, bounds, 800, 600);
assert.equal(player.x, topLeft.x);
assert.equal(player.y, topLeft.y);
const exact = map.mapPoint({ worldX: 0, worldY: 0 }, bounds, 800, 600);
assert.equal(exact.x, 400);
assert.equal(exact.y, 300);
assert.equal(map.category({ kind: "Player", category: "landmarks" }), "player");
const square = map.edgePoint(200, 20, 100, "square");
assert.equal(square.x, 100);
assert.equal(square.y, 10);
const circle = map.edgePoint(200, 200, 100, "circle");
assert.ok(Math.abs(Math.hypot(circle.x, circle.y) - 100) < 1e-6);
const groups = map.layout([{x:20,y:20},{x:28,y:26},{x:21,y:21,pinned:true},{x:120,y:130}]);
assert.equal(groups.length, 3);
assert.equal(groups[0].points.length, 2);
assert.equal(groups[1].points.length, 1);
assert.equal(groups[1].x, 21);
assert.equal(map.layout([{x:NaN,y:5}]).length, 0);
console.log("Map projection, player alignment, edge clipping, and clustering pass.");
